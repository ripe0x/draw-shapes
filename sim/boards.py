#!/usr/bin/env python3
"""Shapes board against Pack boards (docs/IMPLEMENTOR_DECISIONS.md D51, docs/ECONOMICS.md section 2).

Every input is an assumption; every output is a model result, not a forecast. Standard library only;
deterministic. Writes sim/results/boards.md.

Model (src/game/FwaGame.sol `_restock`, src/game/PoolOwner.sol `costOf`, FWAClone):
- A Shape costs its backing plus the 0.001 ETH Shapes mint fee. A Pack (Shape Packs, mainnet 0xf215...5cA7,
  minimum 0.03 ETH) holds the fewest Shapes that make its backing and costs the backing plus 0.001 per Shape
  inside; the makeups below were read from `defaultMakeup` on the pinned fork.
- Listing price = cost x 1.05 (markup). FWA's odds are inverse to price; its fee is the harmonic mean of live prices
  x 1.05 (edge); the owner receives fee - (fee - EV) / 2. Operating allocation 3% of the expected replacement cost.
- The player also pays FWA's VRF fee, about 1.95M gas x gas price, per draw.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MINT = 0.001
MARKUP = 0.05
EDGE = 0.05
OPS = 0.03
VRF_GAS = 1_950_000
SHAPES = [1.0, 0.5, 0.1, 0.05, 0.01]  # Shapes denominations on the mainnet ladder (ETH)


def shapes_in(backing):
    """Shapes in the fewest-Shapes makeup (matches Shape Packs' `defaultMakeup` on the fork)."""
    n, left = 0, round(backing * 100)
    for d in SHAPES:
        k = left // round(d * 100)
        n += k
        left -= k * round(d * 100)
    return n


def cost(kind, backing):
    return backing + MINT * (1 if kind == "S" else shapes_in(backing))


def metrics(rows):
    items = [(k, b, cost(k, b)) for n, k, b in rows for _ in range(n)]
    prices = [c * (1 + MARKUP) for _, _, c in items]
    w = [1 / p for p in prices]
    tw = sum(w)
    probs = [x / tw for x in w]
    ev = len(items) / tw  # harmonic mean of prices
    fee = ev * (1 + EDGE)
    backing = sum(p * b for p, (_, b, _) in zip(probs, items))
    c = sum(p * cc for p, (_, _, cc) in zip(probs, items))
    mint = c - backing
    proceeds = fee - (fee - ev) / 2
    ops = OPS * ev / (1 + MARKUP)
    margin = proceeds - c - ops
    top = max(b for _, b, _ in items)
    p_top = sum(p for p, (_, b, _) in zip(probs, items) if b == top)
    return dict(rows=len(items), board=sum(cc for _, _, cc in items), fee=fee, backing=backing, mint=mint,
                margin=margin, top=top, p_top=p_top, probs=probs, items=items, packs=sum(1 for k, _, _ in items if k == "P"))


BOARDS = [
    ("Shapes (launch default)", [(30, "S", 0.01), (45, "S", 0.05), (25, "S", 0.5)]),
    ("Pack board A: a smoother ladder", [(30, "S", 0.01), (15, "P", 0.03), (25, "S", 0.05), (10, "P", 0.08),
                                         (10, "S", 0.1), (5, "P", 0.25), (5, "S", 0.5)]),
    ("Pack board B: more mid prizes", [(25, "S", 0.01), (20, "P", 0.03), (30, "S", 0.05), (10, "P", 0.15),
                                       (10, "P", 0.3), (5, "S", 1.0)]),
]


def main():
    lines = []
    w = lines.append
    w("# Shapes board against Pack boards\n")
    w("Generated by `sim/boards.py` (deterministic). Assumptions in the file header; model results, not forecasts.\n")
    w("## 1. Boards\n")
    w("| board | rows (Packs) | board cost | ticket (FWA fee) | expected backing | return | mint fees per draw | "
      "mint-fee share of the ticket | owner margin per draw | headline | headline odds |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    res = []
    for name, rows in BOARDS:
        m = metrics(rows)
        res.append((name, m))
        w(f"| {name} | {m['rows']} ({m['packs']}) | {m['board']:.3f} ETH | {m['fee']:.5f} ETH | {m['backing']:.5f} ETH | "
          f"{m['backing'] / m['fee']:.1%} | {m['mint']:.5f} ETH | {m['mint'] / m['fee']:.2%} | {m['margin']:+.5f} ETH | "
          f"{m['top']} ETH | 1 in {1 / m['p_top']:.0f} |")
    w("")
    for name, rows in BOARDS:
        w(f"- {name}: " + ", ".join(f"{n} x {b} {'Pack' if k == 'P' else 'Shape'}" for n, k, b in rows))
    w("")
    w("## 2. Return net of VRF\n")
    w("The player pays the ticket plus FWA's VRF fee. `return` = expected backing / (ticket + VRF); `at least the cost`")
    w("is the chance the prize's backing is at least what the draw cost (not a profit chance: the prize is a Shape or")
    w("Pack, redeemable for its backing).\n")
    w("| board | gas price | VRF fee | return net of VRF | at least the cost |")
    w("|---|---|---|---|---|")
    for name, m in res:
        for g in (0.5, 1, 2, 5):
            vrf = VRF_GAS * g * 1e-9
            total = m["fee"] + vrf
            p_win = sum(p for p, (_, b, _) in zip(m["probs"], m["items"]) if b >= total)
            w(f"| {name} | {g} gwei | {vrf:.5f} ETH | {m['backing'] / total:.1%} | {p_win:.1%} |")
    w("")
    w("## 3. Reading and recommendation\n")
    w("- Packs cost one mint fee per Shape inside, so a Pack of several Shapes costs more to list than a Shape of the")
    w("  same backing; that shows in the mint-fee share and lowers the return slightly. Packs fill the values the")
    w("  Shapes ladder skips (0.03-0.04, 0.06-0.09, 0.15-0.45 ETH), so a board can step more gently from the common")
    w("  prize to the headline.")
    w("- The Shapes board stays the launch default (owner's decision). Board A has seven prize levels, a slightly lower")
    w("  ticket and about the same margin per draw, and needs half the board capital (7.72 against 15.15 ETH); its")
    w("  0.5 ETH headline is rarer (1 in 393 against 1 in 73) because only 5 rows carry it. Board B has a 1 ETH headline")
    w("  (1 in 715) and more mid prizes at a slightly higher ticket and margin, on 12 ETH of board. Either is")
    w("  `BoardPolicy.setBoard` by governance; rows change as they are next vacated, and Pack rows must be at least")
    w("  Shape Packs' 0.03 ETH minimum.")
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    open(os.path.join(HERE, "results", "boards.md"), "w").write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
